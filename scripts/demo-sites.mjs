// Writes lib/demo-sites.js: every demo under demos/<name> that has a site.json
// ({ "host": "<name>.clockworkai.app" }), with its file list, so the middleware
// can serve it on its own subdomain. Tarnhale keeps its own manifest.
// Run: node scripts/demo-sites.mjs   (build.mjs also runs it)
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const demosDir = path.join(root, "demos");

async function walk(d, rel = "") {
  const out = [];
  for (const e of await readdir(d, { withFileTypes: true })) {
    if (e.name.startsWith(".")) continue;
    const r = rel ? `${rel}/${e.name}` : e.name;
    if (e.isDirectory()) out.push(...(await walk(path.join(d, e.name), r)));
    else out.push(r);
  }
  return out;
}

export async function demoSites() {
  const sites = [];
  for (const e of (await readdir(demosDir, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
    if (!e.isDirectory()) continue;
    let cfg;
    try {
      cfg = JSON.parse(await readFile(path.join(demosDir, e.name, "site.json"), "utf8"));
    } catch {
      continue; // no site.json: not served on a subdomain by this manifest
    }
    if (!/^[a-z0-9-]+\.clockworkai\.app$/.test(cfg.host || "")) throw new Error(`demos/${e.name}/site.json: host must be <name>.clockworkai.app`);
    const files = (await walk(path.join(demosDir, e.name))).filter((f) => f !== "site.json").sort();
    sites.push({ name: e.name, host: cfg.host, files });
  }
  return sites;
}

export function sitesSource(sites) {
  return (
    "// Generated by scripts/demo-sites.mjs. Do not edit by hand.\n" +
    "export const DEMO_SITES = " + JSON.stringify(sites.map((s) => ({ ...s, files: s.files })), null, 1) + ";\n"
  );
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const sites = await demoSites();
  await writeFile(path.join(root, "lib", "demo-sites.js"), sitesSource(sites));
  console.log(`demo sites: ${sites.map((s) => `${s.host} (${s.files.length} files)`).join(", ") || "none"}`);
}
