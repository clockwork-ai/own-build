// Writes lib/tarnhale-files.js: every file under demos/tarnhale, so the
// middleware knows which paths exist on tarnhale.clockworkai.app.
// Run: node scripts/tarnhale-manifest.mjs   (build.mjs also runs it)
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const dir = path.join(root, "demos", "tarnhale");

async function walk(d, rel = "") {
  const out = [];
  for (const e of await readdir(d, { withFileTypes: true })) {
    if (e.name.startsWith(".")) continue;
    const r = rel ? `${rel}/${e.name}` : e.name;
    if (e.isDirectory()) out.push(...(await walk(path.join(d, e.name), r)));
    else out.push(r);
  }
  return out;
}

export async function tarnhaleFiles() {
  return (await walk(dir)).sort();
}

export function manifestSource(files) {
  return (
    "// Generated by scripts/tarnhale-manifest.mjs. Do not edit by hand.\n" +
    "export const TARNHALE_FILES = new Set(" + JSON.stringify(files, null, 1) + ");\n"
  );
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const files = await tarnhaleFiles();
  await writeFile(path.join(root, "lib", "tarnhale-files.js"), manifestSource(files));
  console.log(`tarnhale manifest: ${files.length} files`);
}
